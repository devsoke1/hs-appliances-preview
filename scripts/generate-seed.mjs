/**
 * Generates database/seed.sql from the site's current content, so nothing is retyped or lost:
 *   - all services from src/data/services/*.ts (intro + sections → HTML, faults, FAQs,
 *     compliance notes, SEO titles/descriptions from src/data/seo.ts)
 *   - all blog posts from content/blog/*.md (→ Insights)
 *   - legacy WordPress service slugs → slug_redirects
 *   - default settings (contact details from src/data/business.ts)
 * No reviews are seeded — only real reviews should ever be added (via the admin panel).
 *
 *   npm run db:seed-sql
 *
 * SQL is portable: strings use '' quoting only (no backslash escapes), JSON is built with
 * JSON_ARRAY()/JSON_OBJECT() so it's valid in MySQL, MariaDB and SQLite.
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { marked } from "marked";
import { services } from "../src/data/services/index.ts";
import { business } from "../src/data/business.ts";
import { serviceDescription, serviceTitle } from "../src/data/seo.ts";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "database", "seed.sql");

/* ── SQL helpers ── */
const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  const s = String(v);
  if (s.includes("\\")) throw new Error(`Backslash in seed data would be mangled by MySQL: ${s.slice(0, 80)}`);
  return `'${s.replace(/'/g, "''")}'`;
};
const jsonArrayOfObjects = (rows, keys) =>
  rows.length ? `JSON_ARRAY(${rows.map((r) => `JSON_OBJECT(${keys.map((k) => `${q(k)}, ${q(r[k])}`).join(", ")})`).join(", ")})` : "JSON_ARRAY()";
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/* ── Services ── */
// Mirrors src/components/ServiceIcon.tsx (lucide icon names)
const ICONS = {
  "washing-machine-repair": "WashingMachine",
  "fridge-freezer-repair": "Refrigerator",
  "american-fridge-repair": "Container",
  "dishwasher-repair": "UtensilsCrossed",
  "electric-cooker-repair": "CookingPot",
  "electric-hob-repair": "Zap",
  "gas-cooker-repair": "Flame",
  "gas-hob-repair": "Flame",
  "microwave-repair": "Microwave",
  "air-conditioning-repair": "AirVent",
  "cold-room-repair": "Warehouse",
  "dairy-cabinet-repair": "Milk",
  "display-fridge-repair": "Store",
  "bar-cooler-repair": "Beer",
  "cellar-cooler-repair": "Thermometer",
  "ice-machine-repair": "Snowflake",
};
// Shown on the homepage first (editable in the admin)
const FEATURED = new Set([
  "washing-machine-repair", "fridge-freezer-repair", "american-fridge-repair", "dishwasher-repair",
  "electric-cooker-repair", "cold-room-repair", "display-fridge-repair", "ice-machine-repair",
]);

const serviceContentHtml = (s) =>
  [
    ...s.intro.map((p) => `<p>${esc(p)}</p>`),
    ...s.sections.flatMap((sec) => [`<h2>${esc(sec.heading)}</h2>`, ...sec.paragraphs.map((p) => `<p>${esc(p)}</p>`)]),
  ].join("\n");

const lines = [];
const out = (l = "") => lines.push(l);

out("-- ─────────────────────────────────────────────────────────────────────────────");
out("--  HS Appliances — seed data. Generated by `npm run db:seed-sql` — do not edit by hand.");
out(`--  Generated: ${new Date().toISOString()}`);
out("--  Import AFTER schema.sql, into an EMPTY database (it inserts, it doesn't update).");
out("-- ─────────────────────────────────────────────────────────────────────────────");
out("SET NAMES utf8mb4;");
out("SET time_zone = '+00:00';");
out();
out(`-- Services (${services.length})`);
services.forEach((s, i) => {
  const cols = {
    slug: q(s.slug),
    name: q(s.title),
    menu_label: q(s.name),
    category: q(s.category),
    short_description: q(s.shortDescription),
    content: q(serviceContentHtml(s)),
    common_faults: jsonArrayOfObjects(s.faults.map((f) => ({ name: f.name, detail: f.detail })), ["name", "detail"]),
    faqs: jsonArrayOfObjects(s.faqs.map((f) => ({ question: f.question, answer: f.answer })), ["question", "answer"]),
    compliance_note: q(s.complianceNote ?? null),
    image: "NULL",
    image_alt: "NULL",
    icon: q(ICONS[s.slug] ?? "Wrench"),
    meta_title: q(serviceTitle(s)),
    meta_description: q(serviceDescription(s)),
    sort_order: q((i + 1) * 10),
    is_featured: q(FEATURED.has(s.slug) ? 1 : 0),
    is_active: "1",
  };
  out(`INSERT INTO services (${Object.keys(cols).join(", ")}) VALUES (${Object.values(cols).join(", ")});`);
});
out();

/* ── Posts ── */
const BLOG = path.join(ROOT, "content", "blog");
const CATEGORY_BY_SERVICE = {
  "washing-machine-repair": "Laundry",
  "dishwasher-repair": "Laundry & Dishwashers",
  "fridge-freezer-repair": "Fridges & Freezers",
  "american-fridge-repair": "Fridges & Freezers",
  "cold-room-repair": "Commercial Refrigeration",
};
const serviceBySlug = Object.fromEntries(services.map((s) => [s.slug, s]));
const files = fs.existsSync(BLOG) ? fs.readdirSync(BLOG).filter((f) => f.endsWith(".md")).sort() : [];
out(`-- Insights / posts (${files.length})`);
for (const file of files) {
  const { data, content } = matter(fs.readFileSync(path.join(BLOG, file), "utf8"));
  const date = data.date instanceof Date ? data.date.toISOString().slice(0, 10) : String(data.date);
  const svc = data.service ? serviceBySlug[data.service] : undefined;
  const tags = [svc?.name, ...(data.areas ?? []).map((a) => a.charAt(0).toUpperCase() + a.slice(1))].filter(Boolean).join(", ");
  const html = marked.parse(content, { async: false, gfm: true }).trim();
  const cols = {
    slug: q(file.replace(/\.md$/, "")),
    title: q(data.title),
    excerpt: q(data.description),
    content: q(html),
    featured_image: "NULL",
    image_alt: "NULL",
    category: q(CATEGORY_BY_SERVICE[data.service] ?? "Guides"),
    tags: q(tags),
    author: q(business.name),
    meta_title: q(data.seoTitle ?? data.title),
    meta_description: q(data.description),
    status: q("published"),
    published_at: q(`${date} 09:00:00`),
    created_at: q(`${date} 09:00:00`),
  };
  out(`INSERT INTO posts (${Object.keys(cols).join(", ")}) VALUES (${Object.values(cols).join(", ")});`);
}
out();

/* ── Legacy slugs → redirects ── */
out("-- Old WordPress service URLs (e.g. /washing-machine/) → current slugs");
for (const s of services) {
  const old = s.legacyPath.replace(/^\/|\/$/g, "");
  if (old && old !== s.slug) out(`INSERT INTO slug_redirects (type, old_slug, new_slug) VALUES ('service', ${q(old)}, ${q(s.slug)});`);
}
out();

/* ── Settings ── */
const address = `${business.address.street}, ${business.address.locality}, ${business.address.postcode}`;
const settings = {
  homepage_services_limit: "8",
  google_rating: "",       // fill in from your Google Business Profile — leave empty until real
  google_review_count: "",
  google_reviews_url: "",
  phone: business.phone.display,
  email: business.email,
  address,
};
out("-- Settings");
for (const [k, v] of Object.entries(settings)) out(`INSERT INTO settings (setting_key, setting_value) VALUES (${q(k)}, ${q(v)});`);
out();
out("-- No reviews are seeded on purpose: add real reviews in /hs-admin/.");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`✓ ${path.relative(ROOT, OUT)}: ${services.length} services, ${files.length} posts, settings, redirects`);
